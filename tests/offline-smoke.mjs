import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createServer } from "node:http";
import path from "node:path";
import { marketFixture } from "./fixtures/workspace.js";
import { importWorkspace } from "../src/funds/workspace.js";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = marketFixture();
input.tasks[0].title = '</script><script>window.__seedInjected=true</script>';
await writeFile("/tmp/rd-offline-fixture.rdfundos", JSON.stringify(input), { mode: 0o600 });
execFileSync(process.execPath, ["scripts/build-offline.mjs", "--workspace", "/tmp/rd-offline-fixture.rdfundos", "--output", "/tmp/rd-offline-fixture.html"], { cwd: root });
assert.throws(() => execFileSync(process.execPath, ["scripts/build-offline.mjs", "--workspace", "/tmp/rd-offline-fixture.rdfundos", "--output", "dist/private.html"], { cwd: root, stdio: "pipe" }));
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
// Este Chromium gerenciado bloqueia URLs file:. Servir só o HTML por loopback
// preserva o mesmo bundle independente; as interações são executadas offline.
const html = await readFile("/tmp/rd-offline-fixture.html");
const server = createServer((req, res) => { res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" }); res.end(html); });
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
server.unref();
const url = `http://127.0.0.1:${server.address().port}/`;
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [], network = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("request", (request) => { if (/^https?:/.test(request.url()) && request.url() !== url) network.push(request.url()); });
await page.goto(url);
await context.setOffline(true);
await page.getByText("Carteira privada · arquivo de trabalho", { exact: true }).waitFor();
assert.equal(await page.evaluate(() => window.__seedInjected), undefined);
await page.getByRole("navigation").getByRole("button", { name: "Pontos de atenção", exact: true }).click();
await page.getByRole("button", { name: "Desempenho", exact: true }).click();
await page.getByRole("heading", { name: "Revisar posição de teste" }).waitFor();
await page.getByRole("button", { name: "Acompanhar", exact: true }).click();
await page.getByLabel("Próxima revisão", { exact: true }).fill("2026-11-06");
await page.getByRole("dialog").getByRole("button", { name: "Criar acompanhamento", exact: true }).click();
await page.getByRole("navigation").getByRole("button", { name: "Acompanhamento", exact: true }).click();
assert.equal(await page.locator(".fd-task").count(), 2);
await page.getByRole("button", { name: "Registrar decisão", exact: true }).first().click();
await page.getByLabel("Status do atendimento").selectOption("Aguardando cliente");
await page.getByLabel("O que foi conversado ou decidido?").fill("Registro sintético salvo para continuação offline.");
await page.getByRole("button", { name: "Salvar registro", exact: true }).click();
const saving = page.waitForEvent("download");
await page.getByRole("button", { name: "Salvar trabalho", exact: true }).click();
const saved = await saving;
const backup = await readFile(await saved.path(), "utf8");
const restored = importWorkspace(backup);
assert.equal(restored.tasks.length, 2);
assert.equal(restored.tasks[0].status, "Aguardando cliente");
assert.equal(restored.tasks[0].history.at(-1).notes, "Registro sintético salvo para continuação offline.");
await context.setOffline(false);
await page.reload();
await context.setOffline(true);
await page.getByRole("navigation").getByRole("button", { name: "Acompanhamento", exact: true }).click();
assert.equal(await page.locator(".fd-task").count(), 1);
await page.getByRole("button", { name: "Trocar base", exact: true }).click();
await page.getByLabel("Arquivo de carteira").setInputFiles({ name: "backup.rdfundos", mimeType: "application/json", buffer: Buffer.from(backup) });
await page.getByRole("button", { name: "Confirmar e usar esta base" }).click();
await page.getByRole("navigation").getByRole("button", { name: "Acompanhamento", exact: true }).click();
assert.equal(await page.locator(".fd-task").count(), 2);
await page.getByText("Registro sintético salvo para continuação offline.", { exact: true }).waitFor();
await page.getByRole("navigation").getByRole("button", { name: "Realocação", exact: true }).click();
await page.getByRole("heading", { name: "Alternativa sintética", exact: true }).waitFor();
assert.ok((await page.locator(".fd-return-card").last().innerText()).includes("14,00%"));
assert.ok(!/Sharpe|volatilidade|correlação|quartil|taxa adm/i.test(await page.locator(".fd-return-card").last().innerText()));
await page.screenshot({ path: "/tmp/rd-site-comparador.png", fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("navigation").getByRole("button", { name: "Resumo", exact: true }).click();
assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "sem overflow após carregar carteira no mobile");
await page.screenshot({ path: "/tmp/rd-site-mobile.png", fullPage: true });
assert.deepEqual(errors, []);
assert.deepEqual(network, [], "HTML local não faz solicitações HTTP");
await browser.close();
server.close();
console.log("PASS: HTML único servido por loopback; interações sem rede; carteira e alternativas integradas; revisão por conta; decisão e backup restaurados; seed escapado; zero solicitações externas/ativos; mobile sem overflow; dados reais impedidos em dist.");
